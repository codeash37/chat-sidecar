// Generates ../hooks/logos.ts from the simple-icons npm package (CC0 1.0: https://github.com/simple-icons/simple-icons).
// Run from this folder: `npm install && npm run logos`. Keys are the Connectors section's row keys (display name
// lower-cased, a-z0-9 only, with the aliases googleworkspace -> google and metaads -> meta).
// A row key with no icon here gets a letter badge in the pane.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import * as icons from 'simple-icons'

/** Row key -> simple-icons slug. */
const WANTED = {
  gmail: 'gmail',
  googlecalendar: 'googlecalendar',
  googledrive: 'googledrive',
  googlesheets: 'googlesheets',
  googledocs: 'googledocs',
  google: 'google',
  notion: 'notion',
  slack: 'slack',
  stripe: 'stripe',
  calendly: 'calendly',
  figma: 'figma',
  vercel: 'vercel',
  supabase: 'supabase',
  make: 'make',
  youtube: 'youtube',
  shopify: 'shopify',
  meta: 'meta',
  attio: 'attio',
  fireflies: 'fireflies',
  kit: 'kit',
  circle: 'circle',
  vidiq: 'vidiq',
  posthog: 'posthog',
  apify: 'apify',
  higgsfield: 'higgsfield',
  anymailfinder: 'anymailfinder',
  composio: 'composio',
  firecrawl: 'firecrawl',
  pipedrive: 'pipedrive',
  pandadoc: 'pandadoc',
  github: 'github',
  linear: 'linear',
  hubspot: 'hubspot',
  reddit: 'reddit',
  chrome: 'googlechrome',
}

const bySlug = new Map(Object.values(icons).filter(i => i && typeof i === 'object' && 'slug' in i).map(i => [i.slug, i]))
const found = {}
const missing = []
for (const [key, slug] of Object.entries(WANTED)) {
  const icon = bySlug.get(slug)
  if (icon) found[key] = { title: icon.title, hex: `#${icon.hex.toLowerCase()}`, path: icon.path }
  else missing.push(key)
}

const out = [
  '// Generated by tools/gen-logos.mjs from simple-icons (CC0 1.0). Do not edit by hand: change the script and run it again.',
  '// Marks of their owners, shown only to identify the service.',
  `// No icon in simple-icons (letter badge in the pane): ${missing.join(', ') || 'none'}.`,
  '',
  '/** A 24x24 single-path icon and its brand colour. */',
  'export type Logo = { title: string; hex: string; path: string }',
  '',
  '/** Connector row key -> icon. */',
  'export const LOGOS: Readonly<Record<string, Logo>> = {',
  ...Object.entries(found).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`),
  '}',
  '',
]
writeFileSync(fileURLToPath(new URL('../hooks/logos.ts', import.meta.url)), out.join('\r\n'))
console.log(`logos: ${Object.keys(found).length} icons; letter badge for ${missing.join(', ')}`)
